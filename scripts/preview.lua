-- Render a reproducible palette preview from real dark and light Matugen exports.
local root = vim.fs.dirname(vim.fs.dirname(vim.fs.normalize(vim.fn.fnamemodify(arg[0], ":p"))))
vim.opt.rtp:append(root)
assert(arg[1] and arg[2] and arg[3], "Usage: preview.lua dark.json light.json output.svg")

local engine = require("matugen_nvim_bridge.colors")
local function palette(path)
    return engine.generate(vim.json.decode(table.concat(vim.fn.readfile(path), "\n")))
end

local function escape(value)
    return value:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;"):gsub('"', "&quot;")
end

local svg = {
    '<svg xmlns="http://www.w3.org/2000/svg" width="1040" height="440" viewBox="0 0 1040 440" role="img" aria-labelledby="title description">',
    '<title id="title">matugen-nvim-bridge dark and light palette preview</title>',
    '<desc id="description">The same Lua example and syntax roles using palettes generated by Matugen from a blue seed.</desc>',
    '<rect width="1040" height="440" rx="12" fill="#161a22"/>',
}

local lines = {
    { { "comment", "-- Colors follow your wallpaper." } },
    { { "keyword", "local " }, { "foreground", "palette " }, { "punctuation", "= {" } },
    { { "property", "  primary " }, { "punctuation", "= " }, { "string", '"#4488ee"' }, { "punctuation", "," } },
    { { "property", "  contrast " }, { "punctuation", "= " }, { "number", "4.5" }, { "punctuation", "," } },
    { { "punctuation", "}" } },
    {},
    { { "keyword", "local function " }, { "func", "apply_theme" }, { "punctuation", "(" }, { "foreground", "options" }, { "punctuation", ")" } },
    { { "keyword", "  if " }, { "foreground", "options" }, { "punctuation", "." }, { "property", "enabled " }, { "keyword", "then" } },
    { { "keyword", "    return " }, { "foreground", "palette" }, { "punctuation", "." }, { "property", "primary" } },
    { { "keyword", "  end" } },
    { { "keyword", "end" } },
}

for index, data in ipairs({ palette(arg[1]), palette(arg[2]) }) do
    local x = index == 1 and 16 or 528
    local c, u = data.colors, data.ui
    svg[#svg + 1] = string.format('<rect x="%d" y="16" width="496" height="408" rx="8" fill="%s"/>', x, u.surface)
    svg[#svg + 1] = string.format('<text x="%d" y="50" fill="%s" font-size="18" font-weight="600">%s</text>',
        x + 24, c.foreground, index == 1 and "Dark" or "Light")
    svg[#svg + 1] = string.format('<text x="%d" y="50" fill="%s" font-size="12">MATUGEN NVIM BRIDGE</text>', x + 328, u.primary)
    for line_number, tokens in ipairs(lines) do
        local y = 88 + (line_number - 1) * 23
        if line_number == 7 then
            svg[#svg + 1] = string.format('<rect x="%d" y="%d" width="496" height="23" fill="%s"/>', x, y - 17, u.cursorline)
        end
        svg[#svg + 1] = string.format('<text x="%d" y="%d" fill="%s" font-size="12" text-anchor="end">%d</text>',
            x + 35, y, c.comment, line_number)
        local content = {}
        for _, token in ipairs(tokens) do
            content[#content + 1] = string.format('<tspan fill="%s">%s</tspan>', c[token[1]], escape(token[2]))
        end
        svg[#svg + 1] = string.format('<text x="%d" y="%d" font-size="14" xml:space="preserve">%s</text>',
            x + 53, y, table.concat(content))
    end
    for position, role in ipairs({ "keyword", "func", "string", "type", "number" }) do
        local left = x + 24 + (position - 1) * 94
        svg[#svg + 1] = string.format('<circle cx="%d" cy="383" r="4" fill="%s"/>', left + 4, c[role])
        svg[#svg + 1] = string.format('<text x="%d" y="387" fill="%s" font-size="11">%s</text>', left + 15, c[role], role)
    end
end

svg[1] = svg[1]:gsub('role="img"', 'font-family="ui-monospace, SFMono-Regular, Consolas, monospace" role="img"')
svg[#svg + 1] = "</svg>"
vim.fn.writefile(svg, arg[3])
print("Palette preview written to " .. arg[3])
